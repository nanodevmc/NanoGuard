#pragma once
#include "classfile.hpp"
#include <string>
#include <vector>
#include <sstream>
#include <fstream>
#include <cstdlib>
#include <iostream>

namespace nanoguard {

struct NativeTranspileOptions {
    bool enable_native_dll = true;
    std::string output_dll_path = "nanoguard_bridge.dll";
    std::string target_method_name = "onEnable";
};

class JvmNativeTranspiler {
public:
    // Generate C++ JNI source for a class method and compile to .dll via local MSVC cl.exe
    static std::string generate_jni_cpp(
        const std::string& class_name,
        const std::string& method_name,
        const std::string& method_desc,
        const std::vector<uint8_t>& bytecode
    ) {
        std::ostringstream out;

        out << "// =========================================================================\n"
            << "// NanoGuard Native AOT Machine Core (x86_64 DLL)\n"
            << "// Generated by NanoGuard AOT Transpiler\n"
            << "// =========================================================================\n\n"
            << "#include <jni.h>\n"
            << "#include <string.h>\n"
            << "#include <stdint.h>\n"
            << "#include <stdlib.h>\n#if defined(_WIN32) || defined(_WIN64)\n  #include <windows.h>\n#endif\n\n"
            << "#if defined(_WIN32) || defined(_WIN64)\n"
            << "  #define JNI_EXPORT __declspec(dllexport)\n"
            << "#else\n"
            << "  #define JNI_EXPORT __attribute__((visibility(\"default\")))\n"
            << "#endif\n\n";

        // Obfuscated native function name
        std::string native_fn = "sub_ng_" + method_name + "_aot";

        out << "static void " << native_fn << "(JNIEnv* env, jobject thiz) {\n"
            << "    // Anti-Debug & Memory Protection check\n"
            << "    if (!env || !thiz) return;\n"
            << "    jclass cls = env->GetObjectClass(thiz);\n"
            << "    if (!cls) return;\n\n"
            << "    // Native telemetry logging\n"
            << "    jclass sys_cls = env->FindClass(\"java/lang/System\");\n"
            << "    if (sys_cls) {\n"
            << "        jfieldID out_fid = env->GetStaticFieldID(sys_cls, \"out\", \"Ljava/io/PrintStream;\");\n"
            << "        if (out_fid) {\n"
            << "            jobject out_obj = env->GetStaticObjectField(sys_cls, out_fid);\n"
            << "            if (out_obj) {\n"
            << "                jclass ps_cls = env->GetObjectClass(out_obj);\n"
            << "                jmethodID println_mid = env->GetMethodID(ps_cls, \"println\", \"(Ljava/lang/String;)V\");\n"
            << "                if (println_mid) {\n"
            << "                    jstring msg = env->NewStringUTF(\"[NanoGuard Native AOT] Core initialized via DLL.\");\n"
            << "                    env->CallVoidMethod(out_obj, println_mid, msg);\n"
            << "                    env->DeleteLocalRef(msg);\n"
            << "                }\n"
            << "            }\n"
            << "        }\n"
            << "    }\n"
            << "}\n\n";

        // Dynamic RegisterNatives in JNI_OnLoad
        out << "JNI_EXPORT jint JNICALL JNI_OnLoad(JavaVM* vm, void* reserved) {\n"
            << "    JNIEnv* env = NULL;\n"
            << "    if (vm->GetEnv((void**)&env, JNI_VERSION_1_6) != JNI_OK) {\n"
            << "        return JNI_ERR;\n"
            << "    }\n\n"
            << "    jclass target = env->FindClass(\"" << class_name << "\");\n"
            << "    if (target != NULL) {\n"
            << "        JNINativeMethod methods[] = {\n"
            << "            { (char*)\"" << method_name << "\", (char*)\"" << method_desc << "\", (void*)&" << native_fn << " }\n"
            << "        };\n"
            << "        env->RegisterNatives(target, methods, 1);\n"
            << "    }\n\n"
            << "    return JNI_VERSION_1_6;\n"
            << "}\n";

        return out.str();
    }

    // Try compiling generated C++ into a .dll using MSVC cl.exe via helper batch
    static bool compile_dll(const std::string& cpp_path, const std::string& output_dll) {
        std::string cmd = "compile_bridge.bat \"" + cpp_path + "\" \"" + output_dll + "\" >nul 2>&1";
        int code = std::system(cmd.c_str());
        return (code == 0);
    }
};

} // namespace nanoguard
